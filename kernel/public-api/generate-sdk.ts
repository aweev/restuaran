import type { Kernel } from "@/kernel/kernel"

/**
 * The public API surface of a booted kernel: everything a client (and the
 * generated SDK) needs to talk to it. Collected live so the SDK can never drift
 * from what is actually registered — regenerate with `npm run kernel:sdk`.
 */
export interface KernelSurface {
  commands: string[]
  queries: string[]
  projections: string[]
  modules: Array<{ id: string; name: string; version: string; status?: string }>
  schemaVersion: number
}

export function collectSurface(kernel: Kernel): KernelSurface {
  return {
    commands: kernel.commands.registeredCommands().sort(),
    queries: kernel.queries.registeredQueries().sort(),
    projections: kernel.projections.names().sort(),
    modules: kernel.modules.list().map((m) => ({ ...m })).sort((a, b) => a.id.localeCompare(b.id)),
    schemaVersion: kernel.version,
  }
}

/** Deterministic, status-free view of the surface — embedded in the SDK source. */
function stableSurface(surface: KernelSurface): KernelSurface {
  return {
    commands: [...surface.commands].sort(),
    queries: [...surface.queries].sort(),
    projections: [...surface.projections].sort(),
    modules: [...surface.modules]
      .sort((a, b) => a.id.localeCompare(b.id))
      .map((m) => ({ id: m.id, name: m.name, version: m.version })),
    schemaVersion: surface.schemaVersion,
  }
}

/**
 * "order.addLine" -> "orderAddLine", "get.order" -> "getOrder".
 * Deterministic (types are sorted first) with collision suffixing.
 */
function methodNames(types: string[]): Map<string, string> {
  const used = new Set<string>()
  const out = new Map<string, string>()
  for (const type of [...types].sort()) {
    const parts = type.split(/[^A-Za-z0-9]+/).filter(Boolean)
    let name = parts
      .map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : p.charAt(0).toUpperCase() + p.slice(1)))
      .join("")
    if (!/^[A-Za-z_$]/.test(name)) name = `x${name}`
    let candidate = name
    let n = 2
    while (used.has(candidate)) candidate = `${name}${n++}`
    used.add(candidate)
    out.set(type, candidate)
  }
  return out
}

function quote(value: string): string {
  return JSON.stringify(value)
}

/**
 * Build the full TypeScript source of the public API client. Pure + with
 * sorted inputs, so `npm run kernel:sdk` output is byte-for-byte reproducible.
 */
export function buildSdkSource(surface: KernelSurface): string {
  const stable = stableSurface(surface)
  const cmdMethods = methodNames(stable.commands)
  const qryMethods = methodNames(stable.queries)
  const L: string[] = []

  L.push("// AUTO-GENERATED by `npm run kernel:sdk` — DO NOT EDIT BY HAND.")
  L.push("//")
  L.push("// Public API client for the Restaurant OS kernel (REST: /api/v1).")
  L.push("// Zero dependencies: works in browsers, Node and edge runtimes (global fetch).")
  L.push("//")
  L.push("// Surface captured at generation time:")
  for (const line of JSON.stringify(stable, null, 2).split("\n")) L.push(`//   ${line}`)
  L.push("")
  L.push("export interface RosSdkOptions {")
  L.push('  /** Base URL of the public API. Default: "/api/v1". */')
  L.push("  baseUrl?: string")
  L.push("  /** Public API key (ROS_PUBLIC_API_KEYS). Sent as Authorization: Bearer. */")
  L.push("  apiKey?: string")
  L.push("  /** Inject for testability or environments without a global fetch. */")
  L.push("  fetchImpl?: typeof fetch")
  L.push("}")
  L.push("")
  L.push("export interface SdkErrorBody {")
  L.push("  code: string")
  L.push("  message: string")
  L.push("  details?: Record<string, unknown>")
  L.push("}")
  L.push("")
  L.push("export type SdkCommandResult =")
  L.push("  | { success: true; commandId: string; aggregateId?: string; events: unknown[] }")
  L.push("  | { success: false; commandId: string; error: SdkErrorBody }")
  L.push("")
  L.push("export type SdkQueryResult<T> =")
  L.push("  | { success: true; data: T }")
  L.push("  | { success: false; error: SdkErrorBody }")
  L.push("")
  L.push("export interface SdkMeta {")
  L.push("  schemaVersion: number")
  L.push("  commands: string[]")
  L.push("  queries: string[]")
  L.push("  projections: string[]")
  L.push("  modules: Array<{ id: string; name: string; version: string; status: string }>")
  L.push("}")
  L.push("")
  L.push("export class SdkError extends Error {")
  L.push("  readonly code: string")
  L.push("  readonly details?: Record<string, unknown>")
  L.push("  constructor(code: string, message: string, details?: Record<string, unknown>) {")
  L.push("    super(message)")
  L.push('    this.name = "SdkError"')
  L.push("    this.code = code")
  L.push("    this.details = details")
  L.push("  }")
  L.push("}")
  L.push("")
  L.push("/** Typed client generated from the live kernel surface. */")
  L.push("export class RosSdk {")
  L.push(`  static readonly commandTypes: readonly string[] = ${quoteList(stable.commands)}`)
  L.push(`  static readonly queryTypes: readonly string[] = ${quoteList(stable.queries)}`)
  L.push(`  static readonly projectionNames: readonly string[] = ${quoteList(stable.projections)}`)
  L.push("")
  L.push("  private readonly baseUrl: string")
  L.push("  private readonly apiKey?: string")
  L.push("  private readonly doFetch: typeof fetch")
  L.push("")
  L.push("  constructor(opts: RosSdkOptions = {}) {")
  L.push('    this.baseUrl = (opts.baseUrl ?? "/api/v1").replace(/\\/$/, "")')
  L.push("    this.apiKey = opts.apiKey")
  L.push("    this.doFetch = opts.fetchImpl ?? fetch")
  L.push("  }")

  L.push("")
  L.push("  private headers(): Record<string, string> {")
  L.push('    const headers: Record<string, string> = { "Content-Type": "application/json" }')
  L.push("    if (this.apiKey) headers[\"Authorization\"] = `Bearer ${this.apiKey}`")
  L.push("    return headers")
  L.push("  }")
  L.push("")
  L.push("  private static async readBody(res: Response): Promise<Record<string, unknown>> {")
  L.push("    const text = await res.text()")
  L.push("    if (!text) return {}")
  L.push("    try {")
  L.push("      const parsed = JSON.parse(text) as unknown")
  L.push("      return parsed && typeof parsed === \"object\" ? (parsed as Record<string, unknown>) : {}")
  L.push("    } catch {")
  L.push("      return {}")
  L.push("    }")
  L.push("  }")
  L.push("")
  L.push("  private static guardStatus(res: Response): void {")
  L.push('    if (res.status === 401) throw new SdkError("UNAUTHORIZED", "Invalid or missing API key")')
  L.push(
    '    if (res.status === 503) throw new SdkError("PUBLIC_API_DISABLED", "Public API disabled — set ROS_PUBLIC_API_KEYS")'
  )
  L.push("  }")
  L.push("")
  L.push("  /** Dispatch a kernel command; inspect result.success (business failures are not thrown). */")
  L.push("  async command(commandType: string, payload: Record<string, unknown> = {}): Promise<SdkCommandResult> {")
  L.push("    const res = await this.doFetch(`${this.baseUrl}/commands`, {")
  L.push('      method: "POST",')
  L.push("      headers: this.headers(),")
  L.push("      body: JSON.stringify({ commandType, payload }),")
  L.push("    })")
  L.push("    RosSdk.guardStatus(res)")
  L.push("    const body = await RosSdk.readBody(res)")
  L.push("    if (!(\"success\" in body)) {")
  L.push('      throw new SdkError("HTTP_ERROR", `Command request failed with status ${res.status}`)')
  L.push("    }")
  L.push("    return body as unknown as SdkCommandResult")
  L.push("  }")
  L.push("")
  L.push("  /** Run a kernel query; returns data or throws SdkError. */")
  L.push("  async query<T = unknown>(queryType: string, params: Record<string, unknown> = {}): Promise<T> {")
  L.push("    const qs = new URLSearchParams()")
  L.push('    qs.set("query", queryType)')
  L.push("    for (const [k, v] of Object.entries(params)) {")
  L.push("      if (v === undefined || v === null) continue")
  L.push('      qs.set(k, Array.isArray(v) ? v.join(",") : String(v))')
  L.push("    }")
  L.push("    const res = await this.doFetch(`${this.baseUrl}/queries?${qs.toString()}`, {")
  L.push("      headers: this.headers(),")
  L.push("    })")
  L.push("    RosSdk.guardStatus(res)")
  L.push("    const body = await RosSdk.readBody(res)")
  L.push("    const envelope = body as unknown as SdkQueryResult<T>")
  L.push("    if (!envelope.success) {")
  L.push("      const err = envelope.error")
  L.push(
    '      throw new SdkError(err?.code ?? "QUERY_FAILED", err?.message ?? `Query "${queryType}" failed`, err?.details)'
  )
  L.push("    }")
  L.push("    return envelope.data")
  L.push("  }")

  L.push("")
  L.push("  /** Discovery: registered commands, queries, projections, modules. */")
  L.push("  async meta(): Promise<SdkMeta> {")
  L.push("    const res = await this.doFetch(`${this.baseUrl}/meta`, { headers: this.headers() })")
  L.push("    RosSdk.guardStatus(res)")
  L.push("    const body = await RosSdk.readBody(res)")
  L.push('    if (!("commands" in body)) {')
  L.push('      throw new SdkError("HTTP_ERROR", `Meta request failed with status ${res.status}`)')
  L.push("    }")
  L.push("    return body as unknown as SdkMeta")
  L.push("  }")
  L.push("")
  L.push("  /** Read a live projection state by name. */")
  L.push("  async projection<T = unknown>(name: string): Promise<{ name: string; position: number; state: T }> {")
  L.push(
    "    const res = await this.doFetch(`${this.baseUrl}/queries?projection=${encodeURIComponent(name)}`, {"
  )
  L.push("      headers: this.headers(),")
  L.push("    })")
  L.push("    RosSdk.guardStatus(res)")
  L.push("    const body = await RosSdk.readBody(res)")
  L.push('    if ("error" in body) {')
  L.push("      const err = body.error as SdkErrorBody")
  L.push(
    '      throw new SdkError(err?.code ?? "PROJECTION_FAILED", err?.message ?? `Projection "${name}" failed`)'
  )
  L.push("    }")
  L.push("    return body as unknown as { name: string; position: number; state: T }")
  L.push("  }")
  L.push("")

  for (const type of stable.commands) {
    const method = cmdMethods.get(type)!
    L.push(`  /** Dispatches "${type}". */`)
    L.push(`  ${method}(payload: Record<string, unknown> = {}): Promise<SdkCommandResult> {`)
    L.push(`    return this.command(${quote(type)}, payload)`)
    L.push("  }")
    L.push("")
  }
  for (const type of stable.queries) {
    const method = qryMethods.get(type)!
    L.push(`  /** Runs "${type}". */`)
    L.push(`  ${method}<T = unknown>(params: Record<string, unknown> = {}): Promise<T> {`)
    L.push(`    return this.query<T>(${quote(type)}, params)`)
    L.push("  }")
    L.push("")
  }

  // Drop the trailing blank line inside the class body.
  if (L[L.length - 1] === "") L.pop()
  L.push("}")
  L.push("")
  return L.join("\n")
}

function quoteList(values: string[]): string {
  return `[${values.map(quote).join(", ")}]`
}